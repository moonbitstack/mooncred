"""Write the credential files the new packages are tested against.

Every file here is produced by `openssl` — a certificate request to be read, a PKCS#12 to be
opened, a revocation list and three responses to be judged — so that each reader is measured
against a writer it did not write. The one exception is the tampered request, which is a good
one with a byte of its signature flipped.

Rerun after changing a scenario:

    python scripts/gen_credentials.py

Needs `openssl` on PATH; the keys are new on every run, the expectations are not.
"""

import base64
import pathlib
import shutil
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
PASSPHRASE = "correct horse battery staple"
CBC_CIPHERS = {"aes256": "aes-256-cbc", "aes128": "aes-128-cbc", "3des": "des-ede3-cbc"}


def run(*args, cwd=None):
    result = subprocess.run(["openssl", *args], cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f"openssl {' '.join(args)} failed:\n{result.stderr}")
    return result


def pem_to_der(text):
    body = "".join(line for line in text.splitlines() if not line.startswith("-----"))
    return base64.b64decode(body)


def read(path):
    return pathlib.Path(path).read_text()


def minimal(hexdigits):
    """The octets of a hex string without the leading zeros a DER integer pads with."""
    digits = hexdigits.removeprefix("0x")
    if len(digits) % 2:
        digits = "0" + digits
    return bytes.fromhex(digits).lstrip(b"\x00").hex()


def field(text, label):
    """One number out of `openssl pkey -text`: `modulus:` and the lines under it, or a one-liner
    like `publicExponent: 65537 (0x10001)`."""
    lines = text.splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith(f"{label}:"))
    after = lines[start].split(":", 1)[1].strip()
    if after:
        return minimal(after.split("(")[1].rstrip(")"))
    chunks = []
    for line in lines[start + 1:]:
        if not line.startswith("    "):
            break
        chunks.append(line.strip())
    return minimal("".join(chunks).replace(":", ""))


def write_vectors(path, values):
    out = ["// Generated by scripts/gen_credentials.py; rerun it rather than editing.", ""]
    for name, value in values.items():
        out.append("///|")
        if "\n" in value:
            out.append(f"let {name} : String =")
            out.extend("  #|" + line for line in value.split("\n"))
        else:
            out.append(f'let {name} : String = "{value}"')
        out.append("")
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {len(values)} values to {path.relative_to(ROOT)}")


def authority(work, slug, common_name, days=3650):
    """A self-signed P-256 authority, which every signature in these files is made under."""
    key = work / f"{slug}.key"
    run("genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", key)
    pem = work / f"{slug}.pem"
    run(
        "req", "-x509", "-new", "-key", key, "-out", pem, "-days", str(days),
        "-subj", f"/CN={common_name}",
        "-addext", "basicConstraints=critical,CA:TRUE",
        "-addext", "keyUsage=critical,keyCertSign,cRLSign",
    )
    return key, pem


def leaf(work, slug, common_name, ca_key, ca_pem, *, serial=None, days=365, san=True):
    key = work / f"{slug}.key"
    run("genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", key)
    csr = work / f"{slug}.csr"
    run("req", "-new", "-key", key, "-subj", f"/CN={common_name}", "-out", csr)
    ext = work / f"{slug}.ext"
    ext.write_text(
        "[ default ]\n"
        "basicConstraints=critical,CA:FALSE\n"
        "keyUsage=critical,digitalSignature\n"
        + (f"subjectAltName=DNS:{common_name}\n" if san else ""),
        encoding="utf-8",
    )
    cert = work / f"{slug}.pem"
    extra = ["-set_serial", str(serial)] if serial is not None else ["-CAcreateserial"]
    run(
        "x509", "-req", "-in", csr, "-CA", str(ca_pem), "-CAkey", str(ca_key), *extra,
        "-days", str(days), "-sha256", "-extfile", str(ext), "-extensions", "default",
        "-out", cert,
    )
    return key, cert


# --------------------------------------------------------------------- encrypted keys


def gen_pbe(work):
    key = work / "p256.key"
    run("genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", key)
    plain = work / "p256.pem"
    run("pkcs8", "-topk8", "-nocrypt", "-in", key, "-out", plain)
    values = {"passphrase": PASSPHRASE, "plain_key": read(plain).strip()}
    for name, cipher in CBC_CIPHERS.items():
        out = work / f"{name}.pem"
        run(
            "pkcs8", "-topk8", "-in", key, "-v2", cipher,
            "-passout", f"pass:{PASSPHRASE}", "-out", out,
        )
        values[f"encrypted_{name}"] = read(out).strip()
    out = work / "pbes1.pem"
    run(
        "pkcs8", "-topk8", "-in", key, "-v1", "PBE-SHA1-3DES",
        "-passout", f"pass:{PASSPHRASE}", "-out", out,
    )
    values["encrypted_pbes1_3des"] = read(out).strip()
    write_vectors(SRC / "pbe" / "files_wbtest.mbt", values)


# -------------------------------------------------------------------------- requests


def gen_csr(work):
    values = {}
    key = work / "csr.key"
    run("genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", key)
    out = work / "ec.csr"
    run(
        "req", "-new", "-key", key, "-subj", "/C=GB/O=Mooncred/CN=csr.example.com",
        "-extensions", "v3_req", "-config", str(write_req_config(work)), "-out", out,
    )
    values["request_ec"] = read(out).strip()
    values["key_ec"] = read(key).strip()

    tampered = bytearray(pem_to_der(read(out)))
    tampered[-1] ^= 0x01
    values["request_tampered"] = base64.b64encode(bytes(tampered)).decode()

    rsa = work / "rsa.key"
    run("genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-out", rsa)
    out = work / "rsa.csr"
    run("req", "-new", "-key", rsa, "-subj", "/CN=rsa.example.com", "-out", out)
    values["request_rsa"] = read(out).strip()

    ed = work / "ed.key"
    run("genpkey", "-algorithm", "ED25519", "-out", ed)
    out = work / "ed.csr"
    run("req", "-new", "-key", ed, "-subj", "/CN=ed25519.example.com", "-out", out)
    values["request_ed25519"] = read(out).strip()

    out = work / "bare.csr"
    run("req", "-new", "-key", key, "-subj", "/CN=bare.example.com", "-out", out)
    values["request_bare"] = read(out).strip()
    write_vectors(SRC / "csr" / "files_wbtest.mbt", values)


def write_req_config(work):
    """The config `openssl req` needs so the request carries an extensionRequest.

    `-extensions` names a section, and `req_extensions` is what makes `req` copy that section
    into the request's attributes; without the second line the request comes out bare.
    """
    config = work / "req.cnf"
    config.write_text(
        "[ req ]\n"
        "distinguished_name = dn\n"
        "prompt = no\n"
        "req_extensions = v3_req\n"
        "[ dn ]\n"
        "CN = csr.example.com\n"
        "[ v3_req ]\n"
        "basicConstraints = critical,CA:FALSE\n"
        "keyUsage = critical,digitalSignature,keyEncipherment\n"
        "extendedKeyUsage = serverAuth,clientAuth\n"
        "subjectAltName = DNS:csr.example.com,DNS:*.csr.example.com,IP:192.0.2.7\n",
        encoding="utf-8",
    )
    return config


# --------------------------------------------------------------------------- PKCS#12


def gen_pkcs12(work):
    ca_key, ca_pem = authority(work, "container-ca", "Mooncred Container CA")
    key, cert = leaf(work, "container", "container.example.com", ca_key, ca_pem)
    values = {
        "passphrase": PASSPHRASE,
        "certificate": read(cert).strip(),
        "issuer": read(ca_pem).strip(),
        "key": read(key).strip(),
    }
    for name, extra in (
        ("modern", ["-certfile", str(ca_pem)]),
        ("single", []),
        ("nomac", ["-nomac"]),
    ):
        out = work / f"{name}.p12"
        run(
            "pkcs12", "-export", *extra, "-in", str(cert), "-inkey", str(key),
            "-passout", f"pass:{PASSPHRASE}", "-out", str(out),
        )
        values[name] = out.read_bytes().hex()
    write_vectors(SRC / "pkcs12" / "files_wbtest.mbt", values)


# ------------------------------------------------------------------------ JSON Web Encryption


def gen_jwe(work):
    """An RSA key and a key wrapped to it, so the OAEP path is measured against openssl.

    The moduli are the private key's parts in the order `@rsa.PrivateKey::new` wants them:
    modulus, public exponent, private exponent. A 1024-bit key is used because it is the smallest
    that holds a 32-octet content key under OAEP-256, and the numbers stay readable.
    """
    key = work / "jwe-rsa.pem"
    run("genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:1024", "-out", key)
    text = run("pkey", "-in", str(key), "-text", "-noout").stdout
    values = {
        "rsa_n": field(text, "modulus"),
        "rsa_e": field(text, "publicExponent"),
        "rsa_d": field(text, "privateExponent"),
    }
    cek = work / "jwe-cek.bin"
    cek.write_bytes(bytes(range(32)))
    wrapped = work / "jwe-cek.enc"
    run(
        "pkeyutl", "-encrypt", "-inkey", str(key),
        "-pkeyopt", "rsa_padding_mode:oaep", "-pkeyopt", "rsa_oaep_md:sha256",
        "-pkeyopt", "rsa_mgf1_md:sha256",
        "-in", str(cek), "-out", str(wrapped),
    )
    values["rsa_cek"] = cek.read_bytes().hex()
    values["rsa_wrapped"] = wrapped.read_bytes().hex()
    # The same key in PEM, so the other direction can be checked by hand:
    #
    #     openssl pkeyutl -decrypt -inkey key.pem \
    #       -pkeyopt rsa_padding_mode:oaep -pkeyopt rsa_oaep_md:sha256 \
    #       -pkeyopt rsa_mgf1_md:sha256 -in wrapped.bin
    values["rsa_pem"] = read(key).strip()
    write_vectors(SRC / "jwe" / "files_wbtest.mbt", values)


# ------------------------------------------------------------------------ revocation


def gen_revocation(work):
    values = {}
    ca_key, ca_pem = authority(work, "test-ca", "Mooncred Test CA")
    db = work / "db"
    db.mkdir()
    (db / "index.txt").write_text("", encoding="utf-8")
    (db / "serial").write_text("1000\n", encoding="utf-8")
    (db / "crlnumber").write_text("1000\n", encoding="utf-8")
    config = work / "ca.cnf"
    config.write_text(
        "[ ca ]\ndefault_ca = CA_default\n"
        "[ CA_default ]\n"
        "dir = ./db\ndatabase = $dir/index.txt\nserial = $dir/serial\n"
        "crlnumber = $dir/crlnumber\nnew_certs_dir = $dir\n"
        "certificate = ./test-ca.pem\nprivate_key = ./test-ca.key\n"
        "default_md = sha256\ndefault_days = 365\ndefault_crl_days = 30\n"
        "policy = policy_any\nx509_extensions = leaf_ext\ncrl_extensions = crl_ext\n"
        "[ policy_any ]\ncommonName = optional\n"
        "[ leaf_ext ]\nbasicConstraints = CA:FALSE\n"
        "keyUsage = critical,digitalSignature\n"
        "subjectAltName = DNS:leaf.example.com\n"
        "[ crl_ext ]\nauthorityKeyIdentifier = keyid:always\n",
        encoding="utf-8",
    )

    def issue(slug, common_name):
        key = work / f"{slug}.key"
        run("genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", key)
        csr = work / f"{slug}.csr"
        run("req", "-new", "-key", key, "-subj", f"/CN={common_name}", "-out", csr)
        cert = work / f"{slug}.pem"
        run(
            "ca", "-config", str(config), "-batch", "-in", str(csr), "-out", str(cert),
            "-notext", cwd=work,
        )
        return cert

    good = issue("good", "good.example.com")
    revoked = issue("revoked", "revoked.example.com")
    run(
        "ca", "-config", str(config), "-revoke", str(revoked), "-crl_reason", "keyCompromise",
        cwd=work,
    )
    crl = work / "crl.pem"
    run("ca", "-config", str(config), "-gencrl", "-out", str(crl), cwd=work)
    # A list that says what the others said but expired years ago, so the reader has a case where
    # the answer is stale rather than the certificate being fine.
    expired = work / "crl-expired.pem"
    run(
        "ca", "-config", str(config), "-gencrl",
        "-crl_lastupdate", "20200101000000Z", "-crl_nextupdate", "20200201000000Z",
        "-out", str(expired), cwd=work,
    )
    values.update(
        {
            "authority": read(ca_pem).strip(),
            "good": read(good).strip(),
            "revoked": read(revoked).strip(),
            "crl": read(crl).strip(),
            "crl_expired": read(expired).strip(),
        }
    )

    # A certificate under the same authority that its database never recorded: the responder
    # answers `unknown` for it, which is the third case a caller has to handle.
    _, stray = leaf(work, "stray", "stray.example.com", ca_key, ca_pem, serial=999999)

    for slug, cert in (("good", good), ("revoked", revoked), ("stray", stray)):
        request = work / f"{slug}.req.der"
        run(
            "ocsp", "-issuer", str(ca_pem), "-cert", str(cert), "-no_nonce",
            "-reqout", str(request),
        )
        response = work / f"{slug}.resp.der"
        run(
            "ocsp", "-index", str(db / "index.txt"), "-CA", str(ca_pem),
            "-rsigner", str(ca_pem), "-rkey", str(ca_key),
            "-reqin", str(request), "-respout", str(response),
        )
        values[f"ocsp_{slug}"] = response.read_bytes().hex()
        if slug == "good":
            # The same answer, but valid for one day from the moment it was signed rather than
            # the week the default gives: a response a caller has to notice has aged out.
            stale = work / "good-expired.resp.der"
            run(
                "ocsp", "-index", str(db / "index.txt"), "-CA", str(ca_pem),
                "-rsigner", str(ca_pem), "-rkey", str(ca_key),
                "-reqin", str(request), "-ndays", "1", "-respout", str(stale),
            )
            values["ocsp_expired"] = stale.read_bytes().hex()
    values["stray"] = read(stray).strip()
    write_vectors(SRC / "revoke" / "files_wbtest.mbt", values)


def main():
    work = pathlib.Path(tempfile.mkdtemp(prefix="mooncred-"))
    try:
        gen_pbe(work)
        gen_csr(work)
        gen_pkcs12(work)
        gen_jwe(work)
        gen_revocation(work)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
