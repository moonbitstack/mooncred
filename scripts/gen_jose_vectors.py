"""Write the interoperability vectors: what go-jose and this library make of each other's tokens.

Two directions, recorded once and replayed by the tests:

* go-jose seals a set of messages, and the library opens them;
* `src/examples/interop` seals a set of messages with every parameter pinned, go-jose opens
  them, and the plaintext go-jose recovered is recorded beside the token.

    python3 scripts/gen_jose_vectors.py

Needs a Go toolchain and the module in `scripts/jose_vectors`. The tokens go-jose seals are not
compared byte for byte with anything — it draws its own nonces, as it should — so only the
plaintext it recovered is checked. The tokens this library seals are pinned and are compared.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INTEROP = "src/examples/interop"
JOSE = ROOT / "scripts" / "jose_vectors"


def run(command: list[str], cwd: Path) -> str:
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        sys.exit(f"{' '.join(command)} failed:/n{result.stderr or result.stdout}")
    return result.stdout


def report() -> dict:
    with tempfile.TemporaryDirectory() as scratch:
        ours = Path(scratch) / "ours.json"
        ours.write_text(run(["moon", "run", INTEROP, "--target", "native"], ROOT), encoding="utf-8")
        written = run(["go", "run", ".", str(ours)], JOSE)
    parsed = json.loads(written)
    failed = [entry for entry in parsed["opened"] if entry["error"]]
    if failed:
        sys.exit("go-jose could not open: " + ", ".join(entry["name"] for entry in failed))
    missing = [entry["name"] for entry in parsed["opened"] if not entry["plaintext"]]
    if missing:
        sys.exit("go-jose recovered nothing from: " + ", ".join(missing))
    return parsed


def block(text: str) -> list[str]:
    return ["  #|" + line for line in text.split("\n")]


def write(path: Path, part: dict) -> None:
    out = ["// Generated by scripts/gen_jose_vectors.py; rerun it rather than editing.", ""]
    out.append("///|")
    out.append("let jose_report : String =")
    out.extend(block(json.dumps(part, indent=1, ensure_ascii=False)))
    out.append("")
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")


def main() -> None:
    both = report()
    jws = {
        "version": both["version"],
        "sealed": [e for e in both["sealed"] if e["kind"].startswith("jws")],
        "opened": [e for e in both["opened"] if e["name"].startswith("jws")],
        "ours": {k: v for k, v in both["ours"].items() if k.startswith("jws")},
    }
    jwe = {
        "version": both["version"],
        "sealed": [e for e in both["sealed"] if e["kind"].startswith("jwe")],
        "opened": [e for e in both["opened"] if e["name"].startswith("jwe")],
        "ours": {k: v for k, v in both["ours"].items() if k.startswith("jwe")},
    }
    write(ROOT / "src" / "jwt" / "jose_vectors_test.mbt", jws)
    write(ROOT / "src" / "jwe" / "jose_vectors_test.mbt", jwe)
    print(f"wrote {len(jws['sealed'])} JWS and {len(jwe['sealed'])} JWE vectors from {both['version']}")


if __name__ == "__main__":
    main()
