"""Write the RFC 7520 examples into test vectors.

RFC 7520 is "Examples of Protecting Content Using JSON Object Signing and Encryption":
worked examples of JWS, JWE and JWK, published with the keys and the exact octets they
produce. The examples come from the IETF JOSE cookbook, which is the same material in
machine-readable form, at a pinned commit.

    python3 scripts/gen_rfc7520.py                 download and write the vectors
    python3 scripts/gen_rfc7520.py --from <dir>    read a local checkout of the cookbook instead

A JWS or JWE example is written whole, as the JSON the cookbook publishes, so that a test can
reach every field of it: the input, the keys, the intermediate values the example records, and
the outputs in all three serialisations. A JWK example is a key and nothing else, and is
written as the key.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://raw.githubusercontent.com/ietf-jose/cookbook"
COMMIT = "13692b68bfc18b99557a5b1ed311fd5077bfff04"

# The example numbers, in the order the RFC presents them. The file for each is found by its
# number, so a name recorded here cannot drift from the name the cookbook gives it.
JWK_NUMBERS = ["3_1", "3_2", "3_3", "3_4", "3_5", "3_6"]
JWS_NUMBERS = ["4_1", "4_2", "4_3", "4_4", "4_5", "4_6", "4_7", "4_8"]
JWE_NUMBERS = [
    "5_1", "5_2", "5_3", "5_4", "5_5", "5_6", "5_7",
    "5_8", "5_9", "5_10", "5_11", "5_12", "5_13",
]


def locate(directory: str, numbers: list[str], local: Path | None) -> dict[str, str]:
    """The path of each example, by its number, without a name written down twice."""
    if local is not None:
        names = sorted(p.name for p in (local / directory).iterdir() if p.suffix == ".json")
        chosen = {n: f"{directory}/{n}" for n in names}
    else:
        listing = json.loads(
            urllib.request.urlopen(f"{BASE}/{COMMIT}/{directory}", timeout=60).read().decode()
        )
        chosen = {entry["name"]: f"{directory}/{entry['name']}" for entry in listing}
    out: dict[str, str] = {}
    for number in numbers:
        for name, path in chosen.items():
            if name.startswith(f"{number}."):
                out[number] = path
                break
        else:
            raise SystemExit(f"RFC 7520 has no example {number} in {directory}")
    return out


def fetch(name: str, local: Path | None) -> dict:
    if local is not None:
        return json.loads((local / name).read_text(encoding="utf-8"))
    with urllib.request.urlopen(f"{BASE}/{COMMIT}/{name}", timeout=60) as response:
        return json.loads(response.read().decode("utf-8"))


def block(text: str) -> list[str]:
    """A multi-line JSON body as the `#|` lines a MoonBit string literal is written with."""
    return ["  #|" + line for line in text.split("\n")]


def write_examples(examples: dict[str, str], local: Path | None, options: list[str]) -> list[str]:
    out = ["// Generated by scripts/gen_rfc7520.py; rerun it rather than editing.", ""]
    for name, path in examples.items():
        out.append("///|")
        out.append(f"let rfc7520_{name} : String =")
        out.extend(block(json.dumps(fetch(path, local), indent=2, ensure_ascii=False)))
        out.append("")
    out.extend(options)
    return out


def write_jwk(local: Path | None) -> Path:
    out = ["// Generated by scripts/gen_rfc7520.py; rerun it rather than editing.", ""]
    for name, path in locate("jwk", JWK_NUMBERS, local).items():
        out.append("///|")
        out.append(f"let rfc7520_{name} : String =")
        out.extend(block(json.dumps(fetch(path, local), indent=2, ensure_ascii=False)))
        out.append("")
    target = ROOT / "src" / "jwk" / "rfc7520_vectors_test.mbt"
    target.write_text("\n".join(out), encoding="utf-8", newline="\n")
    return target


def write_jws(local: Path | None) -> Path:
    target = ROOT / "src" / "jwt" / "rfc7520_vectors_test.mbt"
    target.write_text("\n".join(write_examples(locate("jws", JWS_NUMBERS, local), local, [])), encoding="utf-8", newline="\n")
    return target


def write_jwe(local: Path | None) -> Path:
    # The two examples whose parts are also named one by one: the tests written against them
    # read the key, the plaintext and the token, and go on reading them.
    examples = locate("jwe", JWE_NUMBERS, local)
    options: list[str] = []
    for name in ("5_6", "5_8"):
        example = fetch(examples[name], local)
        fields = {
            f"rfc7520_{name}_k": example["input"]["key"]["k"],
            f"rfc7520_{name}_plaintext": example["input"]["plaintext"],
            f"rfc7520_{name}_token": example["output"]["compact"],
        }
        for let, value in fields.items():
            options.append("///|")
            options.append(f"let {let} : String =")
            options.extend(block(value))
            options.append("")
    target = ROOT / "src" / "jwe" / "rfc7520_vectors_test.mbt"
    target.write_text("\n".join(write_examples(examples, local, options)), encoding="utf-8", newline="\n")
    return target


def main() -> None:
    local = None
    if "--from" in sys.argv:
        local = Path(sys.argv[sys.argv.index("--from") + 1])
    for target in (write_jwk(local), write_jws(local), write_jwe(local)):
        print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
