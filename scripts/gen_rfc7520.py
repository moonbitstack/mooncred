"""Write the RFC 7520 examples the library's interfaces can carry into test vectors.

RFC 7520 is "Examples of Protecting Content Using JSON Object Signing and Encryption": worked
examples of JWS, JWE and JWK, published with the keys and the exact octets they produce. The
examples come from the IETF JOSE cookbook, which is the same material in machine-readable form,
at a pinned commit.

    python3 scripts/gen_rfc7520.py                 download and write the vectors
    python3 scripts/gen_rfc7520.py --from <dir>    read a local checkout of the cookbook instead

Only the examples this library states it supports are taken: the compact serialisation of JWE
(§5.6 and §5.8) and the keys of §3. RFC 7520's JWS payloads are not claims sets and its JWE
examples past §5.8 use the JSON serialisations, key management modes or compression this
library does not implement; README's "Conformance" section says which.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://raw.githubusercontent.com/ietf-jose/cookbook"
COMMIT = "13692b68bfc18b99557a5b1ed311fd5077bfff04"

JWK_EXAMPLES = {
    "3_1": "jwk/3_1.ec_public_key.json",
    "3_2": "jwk/3_2.ec_private_key.json",
    "3_3": "jwk/3_3.rsa_public_key.json",
    "3_4": "jwk/3_4.rsa_private_key.json",
    "3_5": "jwk/3_5.symmetric_key_mac_computation.json",
    "3_6": "jwk/3_6.symmetric_key_encryption.json",
}

JWE_EXAMPLES = {
    "5_6": "jwe/5_6.direct_encryption_using_aes-gcm.json",
    "5_8": "jwe/5_8.key_wrap_using_aes-keywrap_with_aes-gcm.json",
}


def fetch(name: str, local: Path | None) -> dict:
    if local is not None:
        return json.loads((local / name).read_text(encoding="utf-8"))
    with urllib.request.urlopen(f"{BASE}/{COMMIT}/{name}", timeout=60) as response:
        return json.loads(response.read().decode("utf-8"))


def block(text: str) -> list[str]:
    """A multi-line JSON body as the `#|` lines a MoonBit string literal is written with."""
    return ["  #|" + line for line in text.split("\n")]


def key_text(key: dict) -> str:
    return json.dumps(key, indent=2, ensure_ascii=False)


def write_jwk(local: Path | None) -> Path:
    out = ["// Generated by scripts/gen_rfc7520.py; rerun it rather than editing.", ""]
    for name, path in JWK_EXAMPLES.items():
        out.append("///|")
        out.append(f"let rfc7520_{name} : String =")
        out.extend(block(key_text(fetch(path, local))))
        out.append("")
    target = ROOT / "src" / "jwk" / "rfc7520_vectors_test.mbt"
    target.write_text("\n".join(out), encoding="utf-8", newline="\n")
    return target


def write_jwe(local: Path | None) -> Path:
    out = ["// Generated by scripts/gen_rfc7520.py; rerun it rather than editing.", ""]
    for name, path in JWE_EXAMPLES.items():
        example = fetch(path, local)
        key = example["input"]["key"]
        fields = {
            f"rfc7520_{name}_k": key["k"],
            f"rfc7520_{name}_plaintext": example["input"]["plaintext"],
            f"rfc7520_{name}_token": example["output"]["compact"],
        }
        for let, value in fields.items():
            out.append("///|")
            out.append(f"let {let} : String =")
            out.extend(block(value))
            out.append("")
    target = ROOT / "src" / "jwe" / "rfc7520_vectors_test.mbt"
    target.write_text("\n".join(out), encoding="utf-8", newline="\n")
    return target


def main() -> None:
    local = None
    if "--from" in sys.argv:
        local = Path(sys.argv[sys.argv.index("--from") + 1])
    for target in (write_jwk(local), write_jwe(local)):
        print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
