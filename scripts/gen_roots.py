"""Write src/roots/bundle.mbt from curl's extract of the Mozilla CA certificate store.

    python scripts/gen_roots.py            # fetch https://curl.se/ca/cacert.pem
    python scripts/gen_roots.py FILE       # use a copy already on disk

The download is checked against the SHA-256 curl publishes beside it.
"""

import hashlib
import pathlib
import re
import sys
import urllib.request

URL = "https://curl.se/ca/cacert.pem"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "roots" / "bundle.mbt"


def fetch():
    with urllib.request.urlopen(URL) as r:
        data = r.read()
    with urllib.request.urlopen(URL + ".sha256") as r:
        want = r.read().decode().split()[0]
    got = hashlib.sha256(data).hexdigest()
    if got != want:
        sys.exit(f"checksum mismatch: {got} != {want}")
    return data.decode()


def main():
    text = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8") if len(sys.argv) > 1 else fetch()
    stamp = re.search(r"as of: \w+ (\w+) +(\d+) [\d:]+ (\d+)", text)
    if stamp is None:
        sys.exit("no 'as of' date in the bundle")
    year, month, day = stamp.group(3), stamp.group(1), stamp.group(2)
    months = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
    version = f"{year}-{months.index(month) + 1:02d}-{int(day):02d}"
    body = text[text.index("\n\n", text.index("## SHA256")) + 2:] if "## SHA256" in text else text
    lines = [l for l in body.replace("\r", "").split("\n")]
    while lines and not lines[-1]:
        lines.pop()
    count = sum(1 for l in lines if l == "-----BEGIN CERTIFICATE-----")
    out = [
        "// Generated by scripts/gen_roots.py from curl's extract of the Mozilla CA store; rerun it",
        "// rather than editing.",
        "",
        "///|",
        "/// The date of the Mozilla store this bundle was extracted from.",
        f'pub let version : String = "{version}"',
        "",
        "///|",
        "/// How many certificates the bundle holds.",
        f"pub let count : Int32 = {count}",
        "",
        "///|",
        "let bundle : String =",
    ]
    out.extend("  #|" + l for l in lines)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{count} certificates, Mozilla store as of {version}")


if __name__ == "__main__":
    main()
